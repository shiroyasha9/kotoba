/// The general pasteboard. Transient writes carry the nspasteboard.org markers so clipboard
/// managers skip them, and promise their text (`PromisedText`), so kotoba learns when the paste target reads it. An
/// actor keeps slow reads (promised data) off the main thread.
actor SystemPasteboard: KotobaCore.Pasteboard {
    private static let transientTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    /// A file promise's types (`NSFilePromiseProvider`, and the pasteboard's names for the legacy
    /// `NSFilesPromisePboardType` and `NSPromiseContentsPboardType`). The source app writes the file only when a paste
    /// asks it, so the promise's data written back promises a file no app will write; it is not read or restored.
    private static let filePromisePrefix = "com.apple.pasteboard.promised-"
    private static let filePromiseTypes: Set<String> = [
        "com.apple.NSFilePromiseItemMetaData", "com.apple.pasteboard.NSFilePromiseID",
        "dyn.ah62d4rv4gu8yc6durvwwa3xmrvw1gkdusm1044pxqyuha2pxsvw0e55bsmwca7d3sbwu",
        "dyn.ah62d4rv4gu8y6y4usm1044pxqzb085xyqz1hk64uqm10c6xenv61a3k",
    ]

    /// The general pasteboard; a named one in the snapshot probe.
    private let pasteboard: NSPasteboard
    private let name: NSPasteboard.Name
    /// Whether kotoba's own windows may have written the clipboard at this change count (`OwnClipboardWrites`).
    private let isOwnWrite: @Sendable (Int) -> Bool
    /// The change count after this adapter's last write: plain data written here, which any thread can read.
    private var writtenCount: Int?
    /// The promise of the latest transient write, kept until the next write: the item does not keep its provider.
    private var promised: PromisedText?

    init(
        name: NSPasteboard.Name = .general,
        isOwnWrite: @escaping @Sendable (Int) -> Bool = { OwnClipboardWrites.shared.mayInclude($0) }
    ) {
        self.name = name
        self.isOwnWrite = isOwnWrite
        pasteboard = NSPasteboard(name: name)
    }

    var changeCount: Int {
        pasteboard.changeCount
    }

    /// Read here, off the main thread, unless kotoba's own windows may have written the clipboard: AppKit fulfils their
    /// promised types (a text view's UTF-16 translation) only on the main thread, so a read here would make it ask the
    /// main thread synchronously ("synchronous promise fulfillment requested from a background thread").
    func snapshot() async -> PasteboardSnapshot {
        let changeCount = pasteboard.changeCount
        guard changeCount != writtenCount, isOwnWrite(changeCount) else { return Self.snapshot(of: pasteboard) }
        return await MainActor.run { [name] in Self.snapshot(of: NSPasteboard(name: name)) }
    }

    /// Stops reading at `PasteboardSnapshot.byteLimit`: each type read makes the owning app render it (a big image
    /// as TIFF and PDF), and the snapshot stays in memory until the restore. The limit applies after each type is
    /// read: the pasteboard tells no size before the data. File promises are skipped (`filePromiseTypes`).
    private static func snapshot(of pasteboard: NSPasteboard) -> PasteboardSnapshot {
        var byteCount = 0
        var items: [[PasteboardSnapshot.Representation]] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var types: [PasteboardSnapshot.Representation] = []
            for type in item.types where !isFilePromise(type) {
                guard let data = item.data(forType: type) else { continue }
                byteCount += data.count
                guard byteCount <= PasteboardSnapshot.byteLimit else {
                    Log.app.notice("The clipboard holds over \(byteCount) bytes; kotoba will not keep it")
                    return PasteboardSnapshot(items: [], isTooLarge: true)
                }
                types.append(.init(type: type.rawValue, data: data))
            }
            if !types.isEmpty { items.append(types) }
        }
        return PasteboardSnapshot(items: items)
    }

    private static func isFilePromise(_ type: NSPasteboard.PasteboardType) -> Bool {
        type.rawValue.hasPrefix(filePromisePrefix) || filePromiseTypes.contains(type.rawValue)
    }

    func write(_ text: String) -> Int {
        promised = nil
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        return wrote()
    }

    /// The text is promised, not written: the pasteboard asks kotoba for it at the first read, on the main thread
    /// (spike, 2026-10-17: one call per write, at the first data read; a listing of the types asks nothing; a reader
    /// waits while kotoba's main thread is busy). The promise adds about 0.5 ms to the target's read. The markers
    /// follow nspasteboard.org: transient (not recorded in a history), concealed, auto-generated (no Copy by the
    /// owner), so Raycast, Maccy, Paste and similar managers skip the item and leave the first read to the paste
    /// target. `.currentHostOnly` keeps it off Universal Clipboard ("available only on the current device").
    func writeTransient(_ text: String, onRead: @escaping @Sendable () -> Void) -> Int {
        _ = pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        for type in Self.transientTypes {
            item.setData(Data(), forType: type)
        }
        let promise = PromisedText(text, onRead: onRead)
        item.setDataProvider(promise, forTypes: [.string])
        promised = promise
        pasteboard.writeObjects([item])
        return wrote()
    }

    /// Notes this write's change count (`writtenCount`) and returns it.
    private func wrote() -> Int {
        let count = pasteboard.changeCount
        writtenCount = count
        return count
    }

    /// Writes every type back in its order, the nspasteboard.org markers included: a password a manager copied comes
    /// back concealed and transient, so managers still skip it (lead, 2026-10-17: it was the owner's clipboard, so it
    /// comes back; the manager's own timed clear no longer sees its change count).
    func restore(_ snapshot: PasteboardSnapshot, ifChangeCount changeCount: Int) -> Bool {
        guard pasteboard.changeCount == changeCount else { return false }
        promised = nil
        pasteboard.clearContents()
        let items = snapshot.items.map { types in
            let item = NSPasteboardItem()
            for representation in types {
                item.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type))
            }
            return item
        }
        if !items.isEmpty {
            pasteboard.writeObjects(items)
        }
        _ = wrote()
        return true
    }
}

/// Whether kotoba's own windows may have written the clipboard (a ⌘C in Settings or the Fix window). They write on the
/// main thread, and only while kotoba is active, so a change count that moved during an active spell may be theirs.
/// The notifications keep the counts under a lock, so a snapshot asks with no hop to the main thread.
final class OwnClipboardWrites: Sendable {
    static let shared = OwnClipboardWrites()

    private struct Spells {
        var isActive = false
        /// The change count when kotoba last became active.
        var countAtActivation: Int?
        /// The change count when kotoba last resigned active, if it moved during that spell.
        var countAtResign: Int?
    }

    private let spells = Mutex(Spells())
    /// The observers of activation, kept for the app's life, as `shared` is.
    private let relays = Mutex<[NotificationRelay]>([])

    /// Called once at launch: until then no count counts as kotoba's.
    @MainActor
    func start() {
        if NSApp.isActive { becameActive() }
        let active = NotificationRelay { [self] in becameActive() }
        let resigned = NotificationRelay { [self] in resignedActive() }
        NotificationCenter.default.addObserver(
            active, selector: #selector(NotificationRelay.received), name: NSApplication.didBecomeActiveNotification,
            object: nil)
        NotificationCenter.default.addObserver(
            resigned, selector: #selector(NotificationRelay.received),
            name: NSApplication.didResignActiveNotification, object: nil)
        relays.withLock { $0 = [active, resigned] }
    }

    private func resignedActive() {
        let count = NSPasteboard.general.changeCount
        spells.withLock { spells in
            spells.isActive = false
            if count != spells.countAtActivation { spells.countAtResign = count }
        }
    }

    private func becameActive() {
        let count = NSPasteboard.general.changeCount
        spells.withLock { spells in
            spells.isActive = true
            spells.countAtActivation = count
        }
    }

    /// A count kotoba's windows may have written: one that moved in this active spell, or the one an earlier spell
    /// left (a ⌘C in kotoba, a switch away and back with no copy elsewhere).
    func mayInclude(_ changeCount: Int) -> Bool {
        spells.withLock { spells in
            changeCount == spells.countAtResign || (spells.isActive && changeCount != spells.countAtActivation)
        }
    }
}

/// A transient transcript the pasteboard asks for when an app reads it. The first ask is the paste target's read: the
/// text goes over, then `onRead` runs at once, on this thread, so the pipeline compares the read's moment with the
/// Cmd-V's exactly. The ask is the start of the read, not its end: the pasteboard hands the text to the reader after
/// this returns, and a new clipboard before then gives the reader nothing (spike, 2026-10-19: 380 of 1000 reads lost
/// to a restore at once; `pasteboardFinishedWithDataProvider` comes before the hand-over too). So the restore waits
/// `ClipboardGuard.readSettle`. At quit AppKit asks for every promise, so an unread text stays on the clipboard.
private final class PromisedText: NSObject, NSPasteboardItemDataProvider, Sendable {
    private let text: String
    private let onRead: Mutex<(@Sendable () -> Void)?>

    init(_ text: String, onRead: @escaping @Sendable () -> Void) {
        self.text = text
        self.onRead = Mutex(onRead)
    }

    func pasteboard(
        _ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType
    ) {
        item.setString(text, forType: type)
        onRead.withLock { $0.take() }?()
    }

    /// Replaced before any read, or read already: nothing to do.
    func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {}
}

/// Posts Cmd-V and Return with CGEvent. Needs the Accessibility permission. The key code for "v" comes from
/// the current keyboard layout, so Dvorak and AZERTY work. Text Input Sources must be read on the
/// main thread, so the key code is looked up there at launch and on each layout change, and
/// `sendPaste` reads only the cached value.
struct CGEventPaster: Paster {
    enum PasteError: Error {
        case notAllowed
        case noEvent
        /// The owner holds a modifier that would change each Backspace.
        case modifierHeld
    }

    private static let vKeyCode = Mutex(CGKeyCode(kVK_ANSI_V))
    /// One event source for every paste. CGEventSource is a CF object that is safe to share; Swift
    /// does not mark it Sendable.
    private struct SharedSource: @unchecked Sendable {
        let source = CGEventSource(stateID: .hidSystemState)
    }
    private static let shared = SharedSource()

    /// Builds one keyboard event off the main thread: the first event in a process costs about 21 ms,
    /// which would otherwise land on the first paste.
    static func warmUp() {
        Task.detached {
            _ = CGEvent(keyboardEventSource: shared.source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
        }
    }
    @MainActor private static var layoutObserver: NotificationRelay?

    /// Looks up the key code now and again whenever the keyboard layout changes, also while another app is in front
    /// (the owner switches layouts there), so a paste never sends the old layout's key.
    @MainActor
    static func trackKeyboardLayout() {
        refreshKeyCode()
        let relay = NotificationRelay { Task { @MainActor in refreshKeyCode() } }
        DistributedNotificationCenter.default().addObserver(
            relay, selector: #selector(NotificationRelay.received),
            name: Notification.Name(kTISNotifySelectedKeyboardInputSourceChanged as String), object: nil,
            suspensionBehavior: .deliverImmediately)
        layoutObserver = relay
    }

    @MainActor
    private static func refreshKeyCode() {
        let keyCode = keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        vKeyCode.withLock { $0 = keyCode }
    }

    func sendPaste() async throws {
        try Self.post(Self.vKeyCode.withLock { $0 }, flags: .maskCommand)
    }

    /// Return is the same key in every layout. Posted after Cmd-V into the same HID event stream, the app reads
    /// it only after it has handled the paste, so no wait is needed between them.
    func sendReturn() async throws {
        try Self.post(CGKeyCode(kVK_Return), flags: [])
    }

    /// Backspace is the same key in every layout. Posted before the Cmd-V into the same event stream, so the app
    /// deletes before it pastes. All or none: every check comes before the first press, and one event pair is posted
    /// `count` times. A modifier the owner holds would join each press (⌥⌫ deletes a word), so then nothing is posted.
    func sendBackspaces(_ count: Int) async throws {
        let held = CGEventSource.flagsState(.combinedSessionState)
        guard held.isDisjoint(with: [.maskCommand, .maskAlternate, .maskControl, .maskShift]) else {
            throw PasteError.modifierHeld
        }
        let (keyDown, keyUp) = try Self.events(CGKeyCode(kVK_Delete), flags: [])
        for _ in 0..<count {
            keyDown.post(tap: .cghidEventTap)
            keyUp.post(tap: .cghidEventTap)
        }
    }

    /// Marks every event kotoba posts, so the hotkey tap lets its own Cmd-V and Return pass ("kotoba" in ASCII).
    static let postedEventTag: Int64 = 0x6B6F_746F_6261

    /// Asks for Accessibility at each post: it can be turned off while kotoba runs, and macOS then drops posted
    /// events with no error, so the text would go nowhere. Not allowed, the text stays on the clipboard (`.copied`).
    /// `AXIsProcessTrusted` reads a cache the system refreshes on each Accessibility change: 0.5 µs a call (p90
    /// 0.6 µs, `swiftc -O` probe, 2026-10-17); the first call in a process (about 11 ms) runs at launch, in
    /// `Readiness`. `CGPreflightPostEventAccess` costs about 3 ms a call.
    private static func post(_ keyCode: CGKeyCode, flags: CGEventFlags) throws {
        let (keyDown, keyUp) = try events(keyCode, flags: flags)
        keyDown.post(tap: .cghidEventTap)
        keyUp.post(tap: .cghidEventTap)
    }

    /// One tagged key-down and key-up, once Accessibility is allowed.
    private static func events(_ keyCode: CGKeyCode, flags: CGEventFlags) throws -> (CGEvent, CGEvent) {
        guard AXIsProcessTrusted() else { throw PasteError.notAllowed }
        let source = shared.source
        guard
            let keyDown = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true),
            let keyUp = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false)
        else { throw PasteError.noEvent }
        for event in [keyDown, keyUp] {
            event.flags = flags
            event.setIntegerValueField(.eventSourceUserData, value: postedEventTag)
        }
        return (keyDown, keyUp)
    }

    /// Finds the key that types `character` in the current layout while ⌘ is held: the paste is ⌘V, and a layout
    /// such as "Dvorak - QWERTY ⌘" switches to QWERTY keys under ⌘, so its base-layer "v" key would send ⌘. instead.
    @MainActor
    private static func keyCode(for character: Character) -> CGKeyCode? {
        guard
            let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
            let pointer = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { return nil }
        let layoutData = Unmanaged<CFData>.fromOpaque(pointer).takeUnretainedValue() as Data
        return layoutData.withUnsafeBytes { bytes -> CGKeyCode? in
            guard let layout = bytes.bindMemory(to: UCKeyboardLayout.self).baseAddress else { return nil }
            for keyCode in 0..<CGKeyCode(128) {
                var deadKeyState: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(
                    layout,
                    keyCode,
                    UInt16(kUCKeyActionDisplay),
                    UInt32((cmdKey >> 8) & 0xFF),
                    UInt32(LMGetKbdType()),
                    OptionBits(kUCKeyTranslateNoDeadKeysBit),
                    &deadKeyState,
                    chars.count,
                    &length,
                    &chars
                )
                if status == noErr, length == 1, String(utf16CodeUnits: chars, count: 1) == String(character) {
                    return keyCode
                }
            }
            return nil
        }
    }
}
