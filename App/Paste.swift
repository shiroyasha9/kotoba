import AppKit
import Carbon
import KotobaCore
import Synchronization

/// The general pasteboard. Transient writes carry the nspasteboard.org markers so clipboard
/// managers skip them. An actor keeps slow reads (promised data) off the main thread.
actor SystemPasteboard: KotobaCore.Pasteboard {
    private static let transientTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    var changeCount: Int {
        NSPasteboard.general.changeCount
    }

    /// Stops reading at `PasteboardSnapshot.byteLimit`: each type read makes the owning app render it (a big image
    /// as TIFF and PDF), and the snapshot stays in memory until the restore.
    func snapshot() -> PasteboardSnapshot {
        var byteCount = 0
        var items: [[String: Data]] = []
        for item in NSPasteboard.general.pasteboardItems ?? [] {
            var types: [String: Data] = [:]
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                byteCount += data.count
                guard byteCount <= PasteboardSnapshot.byteLimit else {
                    Log.app.notice("The clipboard holds over \(byteCount) bytes; kotoba will not keep it")
                    return PasteboardSnapshot(items: [], isTooLarge: true)
                }
                types[type.rawValue] = data
            }
            items.append(types)
        }
        return PasteboardSnapshot(items: items)
    }

    func write(_ text: String, isTransient transient: Bool) -> Int {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if transient {
            for type in Self.transientTypes {
                item.setData(Data(), forType: type)
            }
        }
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    func restore(_ snapshot: PasteboardSnapshot, ifChangeCount changeCount: Int) {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount == changeCount else { return }
        pasteboard.clearContents()
        let items = snapshot.items.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types {
                item.setData(data, forType: NSPasteboard.PasteboardType(type))
            }
            return item
        }
        if !items.isEmpty {
            pasteboard.writeObjects(items)
        }
    }
}

/// Posts Cmd-V and Return with CGEvent. Needs the Accessibility permission. The key code for "v" comes from
/// the current keyboard layout, so Dvorak and AZERTY work. Text Input Sources must be read on the
/// main thread, so the key code is looked up there at launch and on each layout change, and
/// `sendPaste` reads only the cached value.
struct CGEventPaster: Paster {
    enum PasteError: Error {
        case notAllowed
        case noEvent
    }

    private static let vKeyCode = Mutex(CGKeyCode(kVK_ANSI_V))
    /// One event source for every paste. CGEventSource is a CF object that is safe to share; Swift
    /// does not mark it Sendable.
    private struct SharedSource: @unchecked Sendable {
        let source = CGEventSource(stateID: .hidSystemState)
    }
    private static let shared = SharedSource()

    /// Builds one keyboard event off the main thread: the first event in a process costs about 21 ms,
    /// which would otherwise land on the first paste.
    static func warmUp() {
        Task.detached {
            _ = CGEvent(keyboardEventSource: shared.source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
        }
    }
    @MainActor private static var layoutObserver: NotificationRelay?

    /// Looks up the key code now and again whenever the keyboard layout changes, also while another app is in front
    /// (the owner switches layouts there), so a paste never sends the old layout's key.
    @MainActor
    static func trackKeyboardLayout() {
        refreshKeyCode()
        let relay = NotificationRelay { Task { @MainActor in refreshKeyCode() } }
        DistributedNotificationCenter.default().addObserver(
            relay, selector: #selector(NotificationRelay.received),
            name: Notification.Name(kTISNotifySelectedKeyboardInputSourceChanged as String), object: nil,
            suspensionBehavior: .deliverImmediately)
        layoutObserver = relay
    }

    @MainActor
    private static func refreshKeyCode() {
        let keyCode = keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        vKeyCode.withLock { $0 = keyCode }
    }

    func sendPaste() async throws {
        try Self.post(Self.vKeyCode.withLock { $0 }, flags: .maskCommand)
    }

    /// Return is the same key in every layout. Posted after Cmd-V into the same HID event stream, the app reads
    /// it only after it has handled the paste, so no wait is needed between them.
    func sendReturn() async throws {
        try Self.post(CGKeyCode(kVK_Return), flags: [])
    }

    /// Marks every event kotoba posts, so the hotkey tap lets its own Cmd-V and Return pass ("kotoba" in ASCII).
    static let postedEventTag: Int64 = 0x6B6F_746F_6261

    /// Asks for Accessibility at each post: it can be turned off while kotoba runs, and macOS then drops posted
    /// events with no error, so the text would go nowhere. Not allowed, the text stays on the clipboard (`.copied`).
    /// `AXIsProcessTrusted` reads a cache the system refreshes on each Accessibility change: 0.5 µs a call (p90
    /// 0.6 µs, `swiftc -O` probe, 2026-10-17); the first call in a process (about 11 ms) runs at launch, in
    /// `Readiness`. `CGPreflightPostEventAccess` costs about 3 ms a call.
    private static func post(_ keyCode: CGKeyCode, flags: CGEventFlags) throws {
        guard AXIsProcessTrusted() else { throw PasteError.notAllowed }
        let source = shared.source
        guard
            let keyDown = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true),
            let keyUp = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false)
        else { throw PasteError.noEvent }
        for event in [keyDown, keyUp] {
            event.flags = flags
            event.setIntegerValueField(.eventSourceUserData, value: postedEventTag)
        }
        keyDown.post(tap: .cghidEventTap)
        keyUp.post(tap: .cghidEventTap)
    }

    /// Finds the key that types `character` in the current layout while ⌘ is held: the paste is ⌘V, and a layout
    /// such as "Dvorak - QWERTY ⌘" switches to QWERTY keys under ⌘, so its base-layer "v" key would send ⌘. instead.
    @MainActor
    private static func keyCode(for character: Character) -> CGKeyCode? {
        guard
            let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
            let pointer = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { return nil }
        let layoutData = Unmanaged<CFData>.fromOpaque(pointer).takeUnretainedValue() as Data
        return layoutData.withUnsafeBytes { bytes -> CGKeyCode? in
            guard let layout = bytes.bindMemory(to: UCKeyboardLayout.self).baseAddress else { return nil }
            for keyCode in 0..<CGKeyCode(128) {
                var deadKeyState: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(
                    layout,
                    keyCode,
                    UInt16(kUCKeyActionDisplay),
                    UInt32((cmdKey >> 8) & 0xFF),
                    UInt32(LMGetKbdType()),
                    OptionBits(kUCKeyTranslateNoDeadKeysBit),
                    &deadKeyState,
                    chars.count,
                    &length,
                    &chars
                )
                if status == noErr, length == 1, String(utf16CodeUnits: chars, count: 1) == String(character) {
                    return keyCode
                }
            }
            return nil
        }
    }
}
